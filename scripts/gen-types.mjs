#!/usr/bin/env node
// Generates packages/sdk/src/openapi.gen.ts — the entity record types — from
// spec/openapi.json with openapi-typescript (a dev dependency; the output is
// types only, so nothing reaches the runtime bundle).
//
//   node scripts/gen-types.mjs           # write the file
//   node scripts/gen-types.mjs --check   # fail if it is out of date
//
// Only the nine `/v1/entities/*` record schemas and the models they reference
// are emitted, not the whole document: the rest of the surface is typed by
// hand in `types.ts`, and a 276-schema `components` interface would otherwise
// ship in every consumer's `.d.ts`. `src/records.ts` re-exports these under
// the SDK's names.
//
// Records are generated with every property required: the server serializes
// every field of a record — a value it lacks is an explicit `null` or `[]`,
// never a missing key — although the schemas carry no `required` list.

import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

import { writeOrCheck } from './lib/generated.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'spec', 'openapi.json');
const TARGET = join(ROOT, 'packages', 'sdk', 'src', 'openapi.gen.ts');

/** The record behind each `/v1/entities/*` route. */
export const RECORD_ROOTS = [
  'CompanyRecord',
  'PersonRecord',
  'PatentRecord',
  'NewsRecord',
  'TrendRecord',
  'MarketReportRecord',
  'FundingRecord',
  'AcademicReportRecord',
  'JobOpeningRecord',
];

/** `roots` plus every schema they reference, transitively, sorted by name. */
export function schemaClosure(schemas, roots) {
  const seen = new Set();
  const visit = (name) => {
    if (seen.has(name)) return;
    if (!(name in schemas)) throw new Error(`spec/openapi.json has no schema '${name}'`);
    seen.add(name);
    for (const [, ref] of JSON.stringify(schemas[name]).matchAll(/"#\/components\/schemas\/([^"]+)"/g)) {
      visit(ref);
    }
  };
  roots.forEach(visit);
  return [...seen].sort();
}

/**
 * A copy of `schema` without its `title` keywords. Pydantic titles every
 * field after its own name ("Account Name"), which would only repeat each
 * property as a comment; descriptions are kept.
 */
function withoutTitles(schema) {
  if (Array.isArray(schema)) return schema.map(withoutTitles);
  if (schema === null || typeof schema !== 'object') return schema;
  const out = {};
  for (const [key, value] of Object.entries(schema)) {
    if (key === 'title') continue;
    out[key] =
      key === 'properties'
        ? Object.fromEntries(Object.entries(value).map(([name, field]) => [name, withoutTitles(field)]))
        : withoutTitles(value);
  }
  return out;
}

async function render(spec) {
  const schemas = spec.components.schemas;
  const names = schemaClosure(schemas, RECORD_ROOTS);
  const pruned = {
    openapi: spec.openapi,
    info: { title: spec.info.title, version: spec.info.version },
    paths: {},
    components: {
      schemas: Object.fromEntries(names.map((name) => [name, withoutTitles(schemas[name])])),
    },
  };
  const ast = await openapiTS(pruned, { propertiesRequiredByDefault: true, alphabetize: true });
  return [
    '// Generated by scripts/gen-types.mjs from spec/openapi.json. Do not edit:',
    '// change the spec in sproutsdata-py, re-sync it, and regenerate.',
    '',
    astToString(ast),
  ].join('\n');
}

// Imported by the record-coverage test for `RECORD_ROOTS` / `schemaClosure`;
// only generate when run as a script.
if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const spec = JSON.parse(readFileSync(SOURCE, 'utf8'));
  process.exitCode = writeOrCheck(TARGET, await render(spec), process.argv.slice(2), {
    root: ROOT,
    regenerate: 'node scripts/gen-types.mjs',
  });
}
