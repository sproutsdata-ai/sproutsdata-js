// Renders the spec's data tables as TypeScript: the error table, the defaults and the
// retry policy (packages/sdk/src/generated/{error-codes,defaults,retry-policy}.ts).
// Plain data, so the SDK never reads JSON at run time and changing behaviour means
// changing the spec.

import { docLines } from './generated.mjs';

const HEADER = (source) => [
  `// Generated by scripts/generate.mjs from spec/${source}. Do not edit: change the spec`,
  '// in sproutsdata-py, re-sync it, and regenerate.',
  '',
];
const union = (values) => values.map((v, i) => `  | ${JSON.stringify(v)}${i === values.length - 1 ? ';' : ''}`);
const seconds = (value) => Math.round(value * 1000);

/** generated/error-codes.ts from error-codes.json. */
export function renderErrorCodes(spec) {
  const codes = spec.codes.map((c) => c.code);
  const fallbacks = Object.entries(spec.status_fallbacks).filter(([status]) => /^\d+$/.test(status));
  return [
    ...HEADER('error-codes.json'),
    `export const DOCS_BASE = ${JSON.stringify(spec.docs_base)};`,
    `export const PROBLEM_MEDIA_TYPE = ${JSON.stringify(spec.problem_media_type)};`,
    '',
    '/** Every code the server sends an API-key caller. */',
    'export type ErrorCode =',
    ...union(codes),
    '',
    '/** The language-neutral error concepts; each has one error class. */',
    'export type ErrorConcept =',
    ...union(spec.concepts),
    '',
    'export const CONCEPTS: readonly ErrorConcept[] = [',
    ...spec.concepts.map((c) => `  ${JSON.stringify(c)},`),
    '];',
    '',
    '/** What the error table says about one code. */',
    'export interface CodeInfo {',
    '  readonly status: number;',
    '  readonly concept: ErrorConcept;',
    '  /** Whether a call that got this code may be retried. */',
    '  readonly retry: boolean;',
    '}',
    '',
    'export const ERROR_CODES: Readonly<Record<ErrorCode, CodeInfo>> = {',
    ...spec.codes.flatMap((c) => [
      ...docLines(c.meaning, '  '),
      `  ${JSON.stringify(c.code)}: { status: ${c.status}, concept: ${JSON.stringify(c.concept)}, retry: ${c.retry} },`,
    ]),
    '};',
    '',
    '/** The concept for a status, when the code is unknown (or absent). */',
    'export const STATUS_FALLBACKS: Readonly<Record<number, ErrorConcept>> = {',
    ...fallbacks.map(([status, concept]) => `  ${status}: ${JSON.stringify(concept)},`),
    '};',
    '',
  ].join('\n');
}

function wait(spec) {
  return `{ deadlineMs: ${seconds(spec.deadline_seconds)}, pollInitialMs: ${seconds(spec.poll_initial_seconds)}, pollMultiplier: ${spec.poll_multiplier}, pollMaxMs: ${seconds(spec.poll_max_seconds)} }`;
}

/** generated/defaults.ts from defaults.json. Durations are milliseconds, as the JS API takes them. */
export function renderDefaults(spec) {
  const env = spec.env;
  return [
    ...HEADER('defaults.json'),
    '/** How long to wait for work to finish, and how often to look. */',
    'export interface WaitDefaults {',
    '  readonly deadlineMs: number;',
    '  readonly pollInitialMs: number;',
    '  readonly pollMultiplier: number;',
    '  readonly pollMaxMs: number;',
    '}',
    '',
    '/** The client\'s defaults. Durations are milliseconds. */',
    'export interface Defaults {',
    '  readonly baseUrl: string;',
    '  readonly plainHttpHosts: readonly string[];',
    '  readonly apiKeyPattern: RegExp;',
    '  readonly apiKeyMaxLength: number;',
    '  readonly env: { readonly apiKey: string; readonly baseUrl: string };',
    '  readonly deprecatedEnv: { readonly apiKey: string; readonly baseUrl: string };',
    '  readonly timeoutMs: number;',
    '  readonly maxRetries: number;',
    '  readonly backoff: { readonly initialMs: number; readonly capMs: number };',
    '  readonly retryAfterCapMs: number;',
    '  readonly followRedirects: boolean;',
    '  readonly streamIdleTimeoutMs: number;',
    '  readonly runWait: WaitDefaults;',
    '  readonly exportWait: WaitDefaults;',
    '}',
    '',
    'export const DEFAULTS: Defaults = {',
    `  baseUrl: ${JSON.stringify(spec.base_url)},`,
    `  plainHttpHosts: ${JSON.stringify(spec.plain_http_hosts)},`,
    `  apiKeyPattern: /${spec.api_key_pattern}/,`,
    `  apiKeyMaxLength: ${spec.api_key_max_length},`,
    `  env: { apiKey: ${JSON.stringify(env.api_key)}, baseUrl: ${JSON.stringify(env.base_url)} },`,
    `  deprecatedEnv: { apiKey: ${JSON.stringify(env.deprecated.js.api_key)}, baseUrl: ${JSON.stringify(env.deprecated.js.base_url)} },`,
    `  timeoutMs: ${seconds(spec.timeout_seconds)},`,
    `  maxRetries: ${spec.max_retries},`,
    `  backoff: { initialMs: ${seconds(spec.backoff.initial_seconds)}, capMs: ${seconds(spec.backoff.cap_seconds)} },`,
    `  retryAfterCapMs: ${seconds(spec.retry_after_cap_seconds)},`,
    `  followRedirects: ${spec.follow_redirects},`,
    `  streamIdleTimeoutMs: ${seconds(spec.stream_idle_timeout_seconds)},`,
    `  runWait: ${wait(spec.run_wait)},`,
    `  exportWait: ${wait(spec.export_wait)},`,
    '};',
    '',
  ].join('\n');
}

/** generated/retry-policy.ts from retry-policy.json. */
export function renderRetryPolicy(policy) {
  const rows = policy.outcomes.map((row) => {
    const decisions = policy.classes.map((cls) => `${cls}: ${JSON.stringify(row[cls])}`).join(', ');
    const retryAfter = row.retry_after === undefined ? 'null' : JSON.stringify(row.retry_after);
    return [
      '  {',
      `    name: ${JSON.stringify(row.outcome)},`,
      `    network: ${JSON.stringify(row.network ?? [])},`,
      `    statuses: ${JSON.stringify(row.status ?? [])},`,
      `    retryAfter: ${retryAfter},`,
      `    decisions: { ${decisions} },`,
      '  },',
    ].join('\n');
  });
  return [
    ...HEADER('retry-policy.json'),
    "import type { RouteClass } from './operations.js';",
    '',
    "export type Decision = 'retry' | 'raise';",
    "export type NetworkOutcome = 'connect_refused' | 'dns_failure' | 'connect_timeout' | 'read_timeout' | 'reset_after_send';",
    '',
    '/** A kind of failed attempt and, per route class, what to do about it. */',
    'export interface Outcome {',
    '  readonly name: string;',
    '  readonly network: readonly NetworkOutcome[];',
    '  readonly statuses: readonly number[];',
    '  /** Matches only when Retry-After is within (or beyond) the cap; `null`: either. */',
    "  readonly retryAfter: 'within_cap' | 'beyond_cap' | null;",
    '  readonly decisions: Readonly<Record<RouteClass, Decision>>;',
    '}',
    '',
    `export const RETRY_AFTER_CAP_MS = ${seconds(policy.retry_after_cap_seconds)};`,
    '',
    '/** Matched in order; the first row that matches a failed attempt decides. */',
    'export const OUTCOMES: readonly Outcome[] = [',
    ...rows,
    '];',
    '',
  ].join('\n');
}
