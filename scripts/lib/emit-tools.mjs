// Renders packages/sdk/src/tools/specs.gen.ts from spec/tools/: the three tool specs,
// shaping.json and messages.json embedded as typed data, and each tool's arguments as a
// TypeScript type generated from its input schema.
//
// The data is the spec files' own, value for value: the tool names, schemas, descriptions,
// shaping numbers and every sentence `sproutsdata/tools` writes to a model come from here,
// never from hand-written TypeScript. Embedding it keeps the SDK free of runtime
// dependencies and of JSON reads at run time.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const TOOL_FILES = ['sprouts_search.json', 'sprouts_similar.json', 'sprouts_entity_lookup.json'];
const ARGUMENT_TYPES = {
  sprouts_search: 'SearchArguments',
  sprouts_similar: 'SimilarArguments',
  sprouts_entity_lookup: 'LookupArguments',
};

/** A tool spec without its strict schema, which `src/tools/strict.ts` derives. */
function withoutStrict(spec) {
  return Object.fromEntries(Object.entries(spec).filter(([key]) => key !== 'strict_input_schema'));
}

/** `value` as a TypeScript literal, indented to sit at `depth` levels. */
function literal(value, depth) {
  return JSON.stringify(value, null, 2).replaceAll('\n', `\n${'  '.repeat(depth)}`);
}

/** A schema node as a TypeScript type: read-only, enums as literal unions. */
function typeOf(schema, depth) {
  if (schema.enum !== undefined) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'array':
      return `readonly (${typeOf(schema.items, depth)})[]`;
    case 'object':
      return objectType(schema, depth);
    default:
      throw new Error(`spec/tools: no TypeScript type for schema type ${JSON.stringify(schema.type)}`);
  }
}

function objectType(schema, depth) {
  const required = new Set(schema.required ?? []);
  const pad = '  '.repeat(depth + 1);
  const members = Object.entries(schema.properties ?? {}).map(
    ([name, child]) => `${pad}readonly ${name}${required.has(name) || child.default !== undefined ? '' : '?'}: ${typeOf(child, depth + 1)};`,
  );
  return `{\n${members.join('\n')}\n${'  '.repeat(depth)}}`;
}

export function renderToolSpecs(source) {
  const read = (name) => JSON.parse(readFileSync(join(source, name), 'utf8'));
  // What the tools read at run time: a file's `$comment` and `version` are for its readers.
  const runtime = (spec) => Object.fromEntries(Object.entries(spec).filter(([key]) => key !== '$comment' && key !== 'version'));
  const tools = TOOL_FILES.map((file) => {
    const spec = read(file);
    if (`${spec.name}.json` !== file) throw new Error(`spec/tools/${file} names the tool '${spec.name}'.`);
    return spec;
  });
  return [
    '// Generated by scripts/generate.mjs from spec/tools/. Do not edit: change the spec in',
    '// sproutsdata-py, re-sync it, and regenerate.',
    '',
    "import type { MessagesSpec, ShapingSpec, ToolName, ToolSpecFile } from './types.js';",
    '',
    ...tools.flatMap((spec) => [
      `/** \`${spec.name}\` arguments once checked against its schema, defaults applied. */`,
      `export interface ${ARGUMENT_TYPES[spec.name]} ${typeOf(spec.input_schema, 0)}`,
      '',
    ]),
    '/** One entry per tool file in `spec/tools/`, without its strict schema (derived: `strict.ts`). */',
    'export const TOOL_SPECS: Readonly<Record<ToolName, ToolSpecFile>> = {',
    // The strict schemas are derived at run time (src/tools/strict.ts), not embedded.
    ...tools.map((spec) => `  ${spec.name}: ${literal(withoutStrict(spec), 1)},`),
    '};',
    '',
    '/** `spec/tools/shaping.json`: the numbers and tables results are shaped with. */',
    `export const SHAPING: ShapingSpec = ${literal(runtime(read('shaping.json')), 0)};`,
    '',
    '/** `spec/tools/messages.json`: every sentence the tools write to a model themselves. */',
    `export const MESSAGES: MessagesSpec = ${literal(runtime(read('messages.json')), 0)};`,
    '',
  ].join('\n');
}
