#!/usr/bin/env node
// Generates packages/sdk/src/error-codes.gen.ts from spec/error-codes.json:
// the `ErrorCode` constant, and the code → concept and status → concept
// tables that choose an error's class.
//
//   node scripts/gen-error-codes.mjs           # write the file
//   node scripts/gen-error-codes.mjs --check   # fail if it is out of date
//
// The output is plain data, so the SDK keeps zero runtime dependencies and
// never reads JSON at run time.

import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { docLines, writeOrCheck } from './lib/generated.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'spec', 'error-codes.json');
const TARGET = join(ROOT, 'packages', 'sdk', 'src', 'error-codes.gen.ts');

/** `auth.invalid_key` → `AUTH_INVALID_KEY`; `not_implemented` → `NOT_IMPLEMENTED`. */
function constantName(code) {
  return code.replace(/[.]/g, '_').toUpperCase();
}

function render(spec) {
  const codes = spec.codes;
  const fallbacks = Object.entries(spec.status_fallbacks)
    .filter(([status]) => /^\d+$/.test(status))
    .map(([status, concept]) => [Number(status), concept])
    .sort(([a], [b]) => a - b);
  const concepts = [...new Set([...codes.map((c) => c.concept), ...fallbacks.map(([, c]) => c)])].sort();

  const out = [
    '// Generated by scripts/gen-error-codes.mjs from spec/error-codes.json. Do not edit:',
    '// change the spec in sproutsdata-py, re-sync it, and regenerate.',
    '',
    ...docLines(
      `The closed set of machine-readable error codes the API returns (${codes.length} codes). ` +
        'Compare against `error.code`. A code this release does not list is still ' +
        'mapped: by its HTTP status, then to `APIError`.',
      '',
    ),
    'export const ErrorCode = {',
  ];
  for (const entry of codes) {
    out.push(...docLines(`${entry.status} — ${entry.meaning}`, '  '));
    out.push(`  ${constantName(entry.code)}: '${entry.code}',`);
  }
  out.push(
    '} as const;',
    '',
    'export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];',
    '',
    '/** The language-neutral error concepts of the spec; `errors.ts` maps each to a class. */',
    'export type ErrorConcept =',
    ...concepts.map((concept, i) => `  | '${concept}'${i === concepts.length - 1 ? ';' : ''}`),
    '',
    '/** Every known code and the concept whose class it raises. Checked first. */',
    'export const CODE_CONCEPTS: ReadonlyMap<string, ErrorConcept> = new Map([',
    ...codes.map((entry) => `  ['${entry.code}', '${entry.concept}'],`),
    ']);',
    '',
    '/** The concept for a status when the code is missing or unknown. */',
    'export const STATUS_CONCEPTS: ReadonlyMap<number, ErrorConcept> = new Map([',
    ...fallbacks.map(([status, concept]) => `  [${status}, '${concept}'],`),
    ']);',
    '',
  );
  return out.join('\n');
}

const spec = JSON.parse(readFileSync(SOURCE, 'utf8'));
process.exitCode = writeOrCheck(TARGET, render(spec), process.argv.slice(2), {
  root: ROOT,
  regenerate: 'node scripts/gen-error-codes.mjs',
});
