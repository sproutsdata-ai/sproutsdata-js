#!/usr/bin/env node
// Generates packages/sdk/src/tools/specs.gen.ts from spec/tools/: the three
// tool specs, shaping.json and messages.json, embedded as typed data.
//
//   node scripts/gen-tool-specs.mjs           # write the file
//   node scripts/gen-tool-specs.mjs --check   # fail if it is out of date
//
// The data is the spec files' own, value for value: the tool names, schemas,
// descriptions, shaping numbers and every sentence `sproutsdata/tools` writes
// to a model come from here, never from hand-written TypeScript. Embedding it
// keeps the SDK free of runtime dependencies and of JSON reads at run time.

import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { writeOrCheck } from './lib/generated.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'spec', 'tools');
const TARGET = join(ROOT, 'packages', 'sdk', 'src', 'tools', 'specs.gen.ts');

/** The shared files beside the tool specs; every other `*.json` here is one tool. */
const SHARED_FILES = ['shaping.json', 'messages.json'];

function read(name) {
  return JSON.parse(readFileSync(join(SOURCE, name), 'utf8'));
}

/** `value` as a TypeScript literal, indented to sit at `depth` levels. */
function literal(value, depth) {
  return JSON.stringify(value, null, 2).replaceAll('\n', `\n${'  '.repeat(depth)}`);
}

function render() {
  const toolFiles = readdirSync(SOURCE)
    .filter((name) => name.endsWith('.json') && !SHARED_FILES.includes(name))
    .sort();
  const tools = toolFiles.map((file) => {
    const spec = read(file);
    if (`${spec.name}.json` !== file) {
      throw new Error(`spec/tools/${file} names the tool '${spec.name}'; the file must be '${spec.name}.json'.`);
    }
    return spec;
  });

  return [
    '// Generated by scripts/gen-tool-specs.mjs from spec/tools/. Do not edit:',
    '// change the spec in sprouts-py, re-sync it, and regenerate.',
    '',
    "import type { MessagesSpec, ShapingSpec, ToolName, ToolSpecFile } from './types';",
    '',
    `/** One entry per tool file in \`spec/tools/\` (${tools.length} tools). */`,
    'export const TOOL_SPECS: Readonly<Record<ToolName, ToolSpecFile>> = {',
    ...tools.map((spec) => `  ${spec.name}: ${literal(spec, 1)},`),
    '};',
    '',
    '/** `spec/tools/shaping.json`: the numbers and tables results are shaped with. */',
    `export const SHAPING: ShapingSpec = ${literal(read('shaping.json'), 0)};`,
    '',
    '/** `spec/tools/messages.json`: every sentence the tools write to a model themselves. */',
    `export const MESSAGES = ${literal(read('messages.json'), 0)} as const satisfies MessagesSpec;`,
    '',
  ].join('\n');
}

process.exitCode = writeOrCheck(TARGET, render(), process.argv.slice(2), {
  root: ROOT,
  regenerate: 'node scripts/gen-tool-specs.mjs',
});
