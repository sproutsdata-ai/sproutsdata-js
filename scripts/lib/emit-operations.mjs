// Renders packages/sdk/src/generated/operations.ts: every operation the SDK wraps, as
// runtime data (method, path, route class, response kind, idempotency, paging; from
// spec/routes.json) and as types (path parameters, query, body and responses; from the
// operations in spec/models.json). The transport's typed `call` derives everything from
// these two, so no resource spells a path, a method or a route class by hand.

import { renderExpr } from './emit-wire.mjs';

/** `lists_add_items` -> `listsAddItems`. */
export function camel(name) {
  return name.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase());
}

const RESPONSE_MARKERS = { csv: "'text/csv'", 'event-stream': "'text/event-stream'" };
const W = 'W.';

/** A success response's type: the model, a marker for a CSV or event-stream body, or `undefined` for none. */
function responseType(node) {
  if (node.prim === 'string' && node.format !== undefined) {
    const marker = RESPONSE_MARKERS[node.format];
    if (marker === undefined) throw new Error(`unknown response format ${node.format}`);
    return marker;
  }
  if (node.prim === 'null') return 'undefined';
  return renderExpr(node, 'output', W);
}

function params(list) {
  if (list.length === 0) return 'Readonly<Record<string, never>>';
  const fields = list.map((p) => `readonly ${p.name}${p.required ? '' : '?'}: ${renderExpr(p.type, 'input', W)};`);
  return `{ ${fields.join(' ')} }`;
}

/** The operation's fields as `key: 'literal'` pairs: the same text is its type and its value. */
function literalFields(route) {
  const paging = route.paging;
  const fields = [
    `method: '${route.method}'`,
    `path: '${route.path}'`,
    `routeClass: '${route.class}'`,
    `response: '${route.response}'`,
    `idempotency: '${route.idempotency}'`,
  ];
  if (paging !== undefined) {
    const parts = [`style: '${paging.style}'`, `items: '${paging.items}'`];
    if (paging.cursor_in !== undefined) parts.push(`cursorIn: '${paging.cursor_in}'`);
    if (paging.binds_limit === true) parts.push('bindsLimit: true');
    fields.push(`paging: { ${parts.join(', ')} }`);
  }
  return fields;
}

const asType = (fields) => fields.map((f) => `readonly ${f.replace('paging: { ', 'paging: { readonly ').replaceAll(', ', '; readonly ')}`).join('; ');

/** The whole of generated/operations.ts. */
export function renderOperations(routes, ir) {
  const sorted = [...routes.routes].sort((a, b) => (a.name < b.name ? -1 : 1));
  const out = [
    '// Generated by scripts/generate.mjs from spec/routes.json and spec/models.json. Do not',
    '// edit: change the spec in sproutsdata-py, re-sync it, and regenerate.',
    '',
    "import type * as W from './wire.js';",
    '',
    "export type Method = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';",
    '/** What repeating a call costs or changes; the retry policy decides from it. */',
    "export type RouteClass = 'safe' | 'billed' | 'keyed' | 'once';",
    "export type ResponseKind = 'json' | 'empty' | 'sse' | 'csv' | 'csv_or_job';",
    "export type Idempotency = 'required' | 'optional' | 'none';",
    '',
    '/** How an operation pages: by an opaque `cursor` (in the body or the query), or by `page` number. */',
    'export interface Paging {',
    "  readonly style: 'cursor' | 'page_number';",
    '  /** The response field that holds the page\'s rows. */',
    '  readonly items: string;',
    "  readonly cursorIn?: 'body' | 'query';",
    '  /** The cursor is bound to `limit` too: the page size must not change between pages. */',
    '  readonly bindsLimit?: true;',
    '}',
    '',
    '/** What the transport knows about one operation. */',
    'export interface OperationSpec {',
    '  readonly method: Method;',
    '  readonly path: string;',
    '  readonly routeClass: RouteClass;',
    '  readonly response: ResponseKind;',
    '  readonly idempotency: Idempotency;',
    '  readonly paging?: Paging;',
    '}',
    '',
    '/** Every operation\'s spec, with each value as its literal type (a test checks each is an `OperationSpec`). */',
    'export interface Operations {',
    ...sorted.map((route) => `  readonly ${camel(route.name)}: { ${asType(literalFields(route))} };`),
    '}',
    '',
    '/** Every operation the SDK wraps, by its SDK name. */',
    'export const OPERATIONS: Operations = {',
    ...sorted.map((route) => `  ${camel(route.name)}: { ${literalFields(route).join(', ')} },`),
    '};',
    '',
    'export type OperationName = keyof Operations;',
    '',
    '/** Each operation\'s path parameters, query, body and responses (by status). */',
    'export interface OperationMap {',
  ];
  for (const route of sorted) {
    const op = ir.operations[route.name];
    const body = op.body === null ? 'undefined' : renderExpr(op.body, 'input', W);
    const responses = Object.entries(op.responses).map(([status, node]) => `${status}: ${responseType(node)}`);
    out.push(
      `  ${camel(route.name)}: {`,
      `    path: ${params(op.path_params)};`,
      `    query: ${params(op.query)};`,
      `    body: ${body};`,
      `    responses: { ${responses.join('; ')} };`,
      '  };',
    );
  }
  out.push('}', '');
  return out.join('\n');
}
